create extension if not exists btree_gist;

create type public.user_role as enum ('student', 'club_lead', 'admin');
create type public.membership_request_status as enum ('pending', 'approved', 'rejected');

create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  role public.user_role not null default 'student',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.clubs (
  id bigint generated by default as identity primary key,
  name text not null unique,
  category text not null,
  venue text not null,
  short_description text not null,
  full_description text not null,
  contact_email text not null,
  lead_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table public.membership_requests (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  message text not null default '',
  status public.membership_request_status not null default 'pending',
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (club_id, student_id)
);

create table public.events (
  id bigint generated by default as identity primary key,
  club_id bigint not null references public.clubs(id) on delete cascade,
  title text not null,
  description text not null default '',
  venue text not null,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  created_by uuid not null references public.profiles(id) on delete restrict,
  created_at timestamptz not null default now(),
  constraint events_valid_time check (ends_at > starts_at),
  exclude using gist (
    venue with =,
    tstzrange(starts_at, ends_at, '[)') with &&
  )
);

create table public.help_desk_messages (
  id bigint generated by default as identity primary key,
  student_id uuid not null references public.profiles(id) on delete cascade,
  club_id bigint references public.clubs(id) on delete cascade,
  subject text not null,
  message text not null,
  created_at timestamptz not null default now()
);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

create or replace function public.is_club_lead(target_club_id bigint)
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select public.is_admin() or exists (
    select 1 from public.clubs
    where id = target_club_id and lead_id = auth.uid()
  );
$$;

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', ''));
  return new;
end;
$$;

create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_user();

alter table public.profiles enable row level security;
alter table public.clubs enable row level security;
alter table public.membership_requests enable row level security;
alter table public.events enable row level security;
alter table public.help_desk_messages enable row level security;

create policy "Users can view their own profile"
  on public.profiles for select to authenticated
  using (id = auth.uid() or public.is_admin());

create policy "Admins can update profiles"
  on public.profiles for update to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Authenticated users can view clubs"
  on public.clubs for select to authenticated
  using (true);

create policy "Admins can manage clubs"
  on public.clubs for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

create policy "Students can view their requests"
  on public.membership_requests for select to authenticated
  using (student_id = auth.uid() or public.is_club_lead(club_id));

create policy "Students can submit requests"
  on public.membership_requests for insert to authenticated
  with check (student_id = auth.uid());

create policy "Club leads can review requests"
  on public.membership_requests for update to authenticated
  using (public.is_club_lead(club_id))
  with check (public.is_club_lead(club_id));

create policy "Authenticated users can view events"
  on public.events for select to authenticated
  using (true);

create policy "Club leads can create events"
  on public.events for insert to authenticated
  with check (public.is_club_lead(club_id) and created_by = auth.uid());

create policy "Club leads can update events"
  on public.events for update to authenticated
  using (public.is_club_lead(club_id))
  with check (public.is_club_lead(club_id));

create policy "Club leads can delete events"
  on public.events for delete to authenticated
  using (public.is_club_lead(club_id));

create policy "Students can view their help requests"
  on public.help_desk_messages for select to authenticated
  using (student_id = auth.uid() or public.is_club_lead(club_id));

create policy "Students can submit help requests"
  on public.help_desk_messages for insert to authenticated
  with check (student_id = auth.uid());
