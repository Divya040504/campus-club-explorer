alter table public.profiles
  add column if not exists avatar_url text,
  add column if not exists bio text not null default '',
  add column if not exists campus text not null default '',
  add column if not exists course text not null default '';

create type public.event_attendance_status as enum ('pending', 'approved', 'rejected');

create table public.event_attendance_requests (
  id bigint generated by default as identity primary key,
  event_id bigint not null references public.events(id) on delete cascade,
  student_id uuid not null references public.profiles(id) on delete cascade,
  status public.event_attendance_status not null default 'pending',
  reviewed_by uuid references public.profiles(id) on delete set null,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  unique (event_id, student_id)
);

create or replace function public.protect_profile_changes()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if old.id = auth.uid() and not public.is_admin() and new.role is distinct from old.role then
    raise exception 'Users cannot change their own role';
  end if;

  return new;
end;
$$;

create trigger protect_profile_changes
  before update on public.profiles
  for each row execute procedure public.protect_profile_changes();

create or replace function public.validate_event_attendance_request()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  if tg_op = 'UPDATE' and (
    new.event_id is distinct from old.event_id
    or new.student_id is distinct from old.student_id
  ) then
    raise exception 'Event attendance requests cannot be reassigned';
  end if;

  if new.status = 'pending' and (new.reviewed_by is not null or new.reviewed_at is not null) then
    raise exception 'Pending attendance requests cannot have review details';
  end if;

  if new.status <> 'pending' and new.reviewed_by is null then
    raise exception 'Reviewed attendance requests require a reviewer';
  end if;

  if tg_op = 'UPDATE' and not public.is_admin() and new.reviewed_by is distinct from auth.uid() then
    raise exception 'Attendance requests must be reviewed by the current user';
  end if;

  return new;
end;
$$;

create trigger validate_event_attendance_request
  before insert or update on public.event_attendance_requests
  for each row execute procedure public.validate_event_attendance_request();

alter table public.event_attendance_requests enable row level security;

grant select, insert, update, delete on public.event_attendance_requests to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "Users can update their own profile"
  on public.profiles for update to authenticated
  using (id = auth.uid())
  with check (id = auth.uid());

create policy "Users can view relevant event attendance requests"
  on public.event_attendance_requests for select to authenticated
  using (
    student_id = auth.uid()
    or public.is_admin()
    or public.is_club_lead((
      select club_id
      from public.events
      where id = event_id
    ))
  );

create policy "Students can request event attendance"
  on public.event_attendance_requests for insert to authenticated
  with check (
    student_id = auth.uid()
    and status = 'pending'
    and reviewed_by is null
    and reviewed_at is null
  );

create policy "Club leads can review event attendance requests"
  on public.event_attendance_requests for update to authenticated
  using (
    public.is_admin()
    or public.is_club_lead((
      select club_id
      from public.events
      where id = event_id
    ))
  )
  with check (
    public.is_admin()
    or public.is_club_lead((
      select club_id
      from public.events
      where id = event_id
    ))
  );

create policy "Students can cancel pending attendance requests"
  on public.event_attendance_requests for delete to authenticated
  using (student_id = auth.uid() and status = 'pending');
